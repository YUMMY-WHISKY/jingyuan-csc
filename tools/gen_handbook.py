class HiddenPage(Flowable):
    """隐藏页：视觉空白 + 白色隐藏文字层（全选/拖选可复制）
       内容：未收录稿·人格融合假说（2026-08-15 替换原 F-07 剧透文案）
       排版（2026-08-15 二修）：改用 Paragraph 标准排版引擎渲染——
       CID 字体的 drawCentredString 宽度测量不准导致偏斜，Paragraph 按字符宽度居中，整齐可靠"""
    def __init__(self, text):
        super().__init__()
        self.text = text
        self._ps = ParagraphStyle('hidden', fontName='STSong-Light', fontSize=11.5,
                                  leading=27, alignment=1, textColor=colors.white)
        self._p = None
    def wrap(self, aw, ah):
        self._p = Paragraph(self.text, self._ps)
        self._w, self._h = self._p.wrap(aw - 4 * cm, ah)
        return aw, ah
    def draw(self):
        c = self.canv
        c.saveState()
        # 水平居中 + 垂直居中
        x = (A4[0] - self._w) / 2
        y = (A4[1] - self._h) / 2
        self._p.drawOn(c, x, y)
        c.restoreState()

